package com.oops.basics.operators;

public class ArithmeticOperator {
    public static void main(String[] args) {
        // +,-,*,/,%
        int num1 = 5;
        int num2 = 10;

        System.out.printf("number1 + number2 = %d\n", num1 + num2);
        System.out.printf("number1 - number2 = %d\n", num1 - num2);
        System.out.printf("number1 * number2 = %d\n", num1 * num2);
        System.out.printf("number1 / number2 = %d\n", num1 / num2);
        System.out.printf("number2 mod number1 = %d\n", num2 % num1);
    }
}
